// ============================================================
// UNMAPPED PRODUCTS
// ============================================================

export function getUnmappedProducts(
  products = []
) {

  return products.filter(
    (product) =>
      !hasMachineImage(
        product.name
      )
  );

}


// ============================================================
// MAPPED PRODUCTS
// ============================================================

export function getMappedProducts(
  products = []
) {

  return products.filter(
    (product) =>
      hasMachineImage(
        product.name
      )
  );

}


// ============================================================
// IMAGE STATISTICS
// ============================================================

export function getMachineImageStatistics(
  products = []
) {

  const total =
    products.length;

  const mapped =
    getMappedProducts(
      products
    ).length;

  const unmapped =
    total - mapped;


  return {

    total,

    mapped,

    unmapped,

    coverage:
      total > 0
        ? `${Math.round(
            (
              mapped /
              total
            ) * 100
          )}%`
        : "0%",

  };

}


