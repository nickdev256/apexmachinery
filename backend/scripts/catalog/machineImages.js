// ============================================================
// GET MACHINE IMAGE
// ============================================================
//
// THIS IS THE FUNCTION YOUR products.js IS IMPORTING.
//
// import { getMachineImage } from "./machineImages.js";
//
// ============================================================

export function getMachineImage(machineName) {

  if (!machineName) {
    return DEFAULT_MACHINE_IMAGE;
  }

  const filename =
    machineImages[machineName];

  if (!filename) {

    console.warn(
      `[Apex Machinery] No image mapped for: ${machineName}`
    );

    return DEFAULT_MACHINE_IMAGE;
  }

  return `${MACHINE_IMAGE_DIRECTORY}/${filename}`;
}


// ============================================================
// CREATE IMAGE KEY
// ============================================================

export function machineImageKey(
  name = ""
) {

  return String(name)
    .normalize("NFKD")
    .replace(
      /[\u0300-\u036f]/g,
      ""
    )
    .toLowerCase()
    .trim()
    .replace(
      /[^a-z0-9]+/g,
      "-"
    )
    .replace(
      /^-+|-+$/g,
      "");
}


// ============================================================
// CREATE IMAGE PATH
// ============================================================

export function createMachineImagePath(
  machineName,
  extension = "jpg"
) {

  if (!machineName) {
    return null;
  }

  const key =
    machineImageKey(
      machineName
    );

  if (!key) {
    return null;
  }

  return `${MACHINE_IMAGE_DIRECTORY}/${key}.${extension}`;
}


// ============================================================
// GET IMAGE CANDIDATES
// ============================================================

export function getMachineImageCandidates(
  machineName
) {

  if (!machineName) {
    return [];
  }

  const key =
    machineImageKey(
      machineName
    );

  if (!key) {
    return [];
  }

  return MACHINE_IMAGE_EXTENSIONS.map(
    (extension) =>
      `${MACHINE_IMAGE_DIRECTORY}/${key}.${extension}`
  );
}


// ============================================================
// CHECK IMAGE
// ============================================================

export function hasMachineImage(
  machineName
) {

  return Boolean(
    machineImages[machineName]
  );

}


// ============================================================
// GET FILENAME
// ============================================================

export function getMachineImageFilename(
  machineName
) {

  if (!machineName) {
    return null;
  }

  return (
    machineImages[machineName] ||
    null
  );

}


